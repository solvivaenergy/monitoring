-- Migration 28 — tiered DU rates readable by the customer portal.
--
-- WHY. The portal prices savings with electricity_rates.rate, one flat ₱/kWh per
-- DU and month. Between 2026-10-09 and 2026-10-15 the DU-rate scrape (source_url
-- "ICSC presyo.icsc.ngo") added the following OUTSIDE this repo, via the SQL
-- editor / Management API:
--
--   electricity_rates.customer_class   residential | commercial, part of the
--                                      unique key (provider, effective_date, class);
--                                      all 368 rows are residential today
--   electricity_rate_tiers             MERALCO's residential schedule: the ₱/kWh
--                                      at each monthly-consumption level, 15 levels
--                                      (50 … 5,000 kWh) × 37 months since 2023-09.
--                                      The other nine DUs have no tiers.
--   insert_electricity_rate(...)       the scrape's write path (rate + tiers jsonb)
--   replace_electricity_rate(...)      delete-then-insert for one provider/date/class
--   rate_for_consumption(rate_id, kwh) the level at or above kwh; above the top
--                                      level the top level; no tiers → the flat rate
--
-- The tier table had RLS on and NO policy, so the portal's login role read nothing
-- from it. This file records that DDL as built (every statement idempotent) and
-- adds the read policy, the same shape as electricity_rates'.
--
-- It also narrows anon/authenticated to SELECT on the three rate tables: Supabase's
-- default privileges had left them INSERT … TRUNCATE; RLS blocks the row writes but
-- not TRUNCATE (the migration-26 finding). The scrape writes as service_role, which
-- keeps its grants.
--
-- Portal side: CustomerPortal src/lib/savings.ts reads the tiers and prices each
-- month's production at the level of that month's total consumption.
--
-- HOW TO RUN: as postgres over the direct connection (autocommit) or the
-- Management API query endpoint. Re-runnable. ROLLBACK (policy and grants only —
-- the as-built objects are the scrape's and stay):
--   drop policy if exists "Allow public read access to electricity_rate_tiers"
--     on public.electricity_rate_tiers;
--   grant all on public.electricity_rates, public.electricity_rate_tiers,
--     public.electricity_providers to anon, authenticated;

alter table public.electricity_rates
  add column if not exists customer_class text not null default 'residential';
-- ///
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'electricity_rates_customer_class_check') then
    alter table public.electricity_rates
      add constraint electricity_rates_customer_class_check
      check (customer_class = any (array['residential'::text, 'commercial'::text]));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'unique_provider_effective_date_class') then
    alter table public.electricity_rates
      add constraint unique_provider_effective_date_class unique (provider_id, effective_date, customer_class);
  end if;
end $$;
-- ///
create table if not exists public.electricity_rate_tiers (
  id              bigint generated by default as identity primary key,
  rate_id         bigint  not null references public.electricity_rates(id) on delete cascade,
  consumption_kwh numeric not null check (consumption_kwh > 0),
  rate_per_kwh    numeric not null check (rate_per_kwh > 0),
  unique (rate_id, consumption_kwh)
);
-- ///
comment on table public.electricity_rate_tiers is
  'Rate per kWh at each consumption level of a tiered schedule. A level covers consumption above the previous level up to and including itself. Schedules with no rows here use electricity_rates.rate.';
-- ///
create or replace function public.insert_electricity_rate(
  p_provider_id bigint, p_effective_date date, p_customer_class text,
  p_rate numeric, p_tiers jsonb, p_source_url text default null)
returns bigint
language plpgsql
as $$
declare
  v_id bigint;
begin
  insert into public.electricity_rates
    (provider_id, effective_date, customer_class, rate, source_url, scraped_at)
  values
    (p_provider_id, p_effective_date, p_customer_class, p_rate, p_source_url, now())
  returning id into v_id;

  insert into public.electricity_rate_tiers (rate_id, consumption_kwh, rate_per_kwh)
  select v_id, (t->>'kwh')::numeric, (t->>'rate')::numeric
  from jsonb_array_elements(coalesce(p_tiers, '[]'::jsonb)) as t;

  return v_id;
end;
$$;
-- ///
create or replace function public.replace_electricity_rate(
  p_provider_id bigint, p_effective_date date, p_customer_class text,
  p_rate numeric, p_tiers jsonb, p_source_url text default null)
returns bigint
language plpgsql
as $$
declare
  v_id bigint;
begin
  delete from public.electricity_rates
   where provider_id    = p_provider_id
     and effective_date = p_effective_date
     and customer_class = p_customer_class;

  v_id := public.insert_electricity_rate(
            p_provider_id, p_effective_date, p_customer_class,
            p_rate, p_tiers, p_source_url);

  return v_id;
end;
$$;
-- ///
create or replace function public.rate_for_consumption(p_rate_id bigint, p_kwh numeric)
returns numeric
language sql
stable
as $$
  select coalesce(
    -- the smallest level at or above the consumption
    (select t.rate_per_kwh
       from public.electricity_rate_tiers t
      where t.rate_id = p_rate_id
        and t.consumption_kwh >= p_kwh
      order by t.consumption_kwh asc
      limit 1),
    -- above the highest level: use the highest level
    (select t.rate_per_kwh
       from public.electricity_rate_tiers t
      where t.rate_id = p_rate_id
        and p_kwh is not null
      order by t.consumption_kwh desc
      limit 1),
    -- no tiers (flat-rate providers), or no consumption: the schedule's rate
    (select r.rate
       from public.electricity_rates r
      where r.id = p_rate_id)
  );
$$;
